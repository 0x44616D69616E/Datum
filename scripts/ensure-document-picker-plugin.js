// scripts/ensure-document-picker-plugin.js
//
// Generates DocumentPickerPlugin.java. Replaces ensure-storage-plugin.js's
// AllFilesAccessPlugin (MANAGE_EXTERNAL_STORAGE / "All files access"),
// which only existed for two things: browsing to an arbitrary folder as
// the storage root, and browsing to a GPX file to import. Both are better
// served by Android's own Storage Access Framework, which needs no special
// permission at all - the user picks a file through the system's own
// document picker (a normal, sandboxed activity), and the result arrives
// as a content:// Uri with a one-time read grant.
//
// Covers both of this plugin's two jobs with one small native surface:
//   - pickFiles(): launches ACTION_OPEN_DOCUMENT with multi-select enabled,
//     reads whatever the user picked through the ContentResolver, and
//     returns their text content directly (small GPX files, no reason to
//     round-trip through a second read call).
//   - openAppSettings(): opens Android's own "App info" screen for Datum.
//     Not tied to any specific permission (there isn't one to request
//     anymore) - a generic escape hatch for "a write is failing, go check
//     Settings" in storage-health's retry flow.
//
// Same idempotent pattern as the other ensure-*-plugin.js scripts: safe to
// run after every single `npx cap sync android`, writes the plugin file
// fresh every time, and only touches MainActivity.java if the plugin isn't
// registered yet.
//
// Usage: node scripts/ensure-document-picker-plugin.js
// (or: npm run fix-manifest, which runs this too)

const fs = require('fs');
const path = require('path');
const { ensurePluginRegistered, findMainActivity } = require('./lib/patchMainActivity');

const projectRoot = path.join(__dirname, '..');
const found = findMainActivity(projectRoot);
if (!found) {
  console.error(
    `Couldn't find MainActivity.java under android/app/src/main/java/ - ` +
    `run "npx cap add android" first if the android/ folder doesn't have one yet.`
  );
  process.exit(1);
}
const { dir: javaDir, packageName, file: mainActivityFile } = found;
const pluginFile = path.join(javaDir, 'DocumentPickerPlugin.java');

const pluginSource = `package ${packageName};

import android.app.Activity;
import android.content.Intent;
import android.database.Cursor;
import android.net.Uri;
import android.provider.OpenableColumns;
import android.provider.Settings;

import androidx.activity.result.ActivityResult;

import com.getcapacitor.JSArray;
import com.getcapacitor.JSObject;
import com.getcapacitor.Plugin;
import com.getcapacitor.PluginCall;
import com.getcapacitor.PluginMethod;
import com.getcapacitor.annotation.ActivityCallback;
import com.getcapacitor.annotation.CapacitorPlugin;

import java.io.ByteArrayOutputStream;
import java.io.InputStream;

// Generated by scripts/ensure-document-picker-plugin.js - safe to
// regenerate, don't hand-edit (changes will be overwritten on the next
// sync).
@CapacitorPlugin(name = "DocumentPicker")
public class DocumentPickerPlugin extends Plugin {

    @PluginMethod
    public void pickFiles(PluginCall call) {
        Intent intent = new Intent(Intent.ACTION_OPEN_DOCUMENT);
        intent.addCategory(Intent.CATEGORY_OPENABLE);
        intent.putExtra(Intent.EXTRA_ALLOW_MULTIPLE, true);
        // GPX has no registered MIME type, and most file managers and mail
        // apps report it as application/octet-stream anyway - the manifest's
        // own GPX intent filter hits the identical problem (see
        // ensure-gpx-intent.js). "*/*" plus the .gpx filtering already done
        // on the JS side is the only reliable combination.
        intent.setType("*/*");
        startActivityForResult(call, intent, "pickFilesResult");
    }

    @ActivityCallback
    private void pickFilesResult(PluginCall call, ActivityResult result) {
        if (call == null) return;
        if (result.getResultCode() != Activity.RESULT_OK || result.getData() == null) {
            // Includes the user backing out with nothing selected - not an
            // error, just nothing picked.
            JSObject empty = new JSObject();
            empty.put("files", new JSArray());
            call.resolve(empty);
            return;
        }

        Intent data = result.getData();
        java.util.List<Uri> uris = new java.util.ArrayList<>();
        if (data.getClipData() != null) {
            // Multi-select result.
            int count = data.getClipData().getItemCount();
            for (int i = 0; i < count; i++) uris.add(data.getClipData().getItemAt(i).getUri());
        } else if (data.getData() != null) {
            // Single-select result.
            uris.add(data.getData());
        }

        JSArray files = new JSArray();
        for (Uri uri : uris) {
            try {
                String name = queryDisplayName(uri);
                String text = readUriAsText(uri);
                JSObject file = new JSObject();
                file.put("name", name);
                file.put("data", text);
                files.put(file);
            } catch (Exception e) {
                // One unreadable file (permission revoked mid-pick, a
                // provider hiccup) shouldn't fail the whole batch - the JS
                // side already handles a picked file that didn't come back.
            }
        }

        JSObject resultObj = new JSObject();
        resultObj.put("files", files);
        call.resolve(resultObj);
    }

    private String readUriAsText(Uri uri) throws Exception {
        InputStream in = getContext().getContentResolver().openInputStream(uri);
        if (in == null) throw new Exception("Could not open the selected file.");
        try {
            ByteArrayOutputStream buffer = new ByteArrayOutputStream();
            byte[] chunk = new byte[8192];
            int n;
            while ((n = in.read(chunk)) != -1) buffer.write(chunk, 0, n);
            return buffer.toString("UTF-8");
        } finally {
            in.close();
        }
    }

    private String queryDisplayName(Uri uri) {
        String name = "import.gpx";
        Cursor cursor = getContext().getContentResolver().query(uri, null, null, null, null);
        if (cursor != null) {
            try {
                int idx = cursor.getColumnIndex(OpenableColumns.DISPLAY_NAME);
                if (idx >= 0 && cursor.moveToFirst()) {
                    String n = cursor.getString(idx);
                    if (n != null && !n.isEmpty()) name = n;
                }
            } finally {
                cursor.close();
            }
        }
        return name;
    }

    @PluginMethod
    public void openAppSettings(PluginCall call) {
        Intent intent = new Intent(Settings.ACTION_APPLICATION_DETAILS_SETTINGS);
        intent.setData(Uri.parse("package:" + getContext().getPackageName()));
        getActivity().startActivity(intent);
        call.resolve();
    }
}
`;

fs.writeFileSync(pluginFile, pluginSource);
console.log(`Wrote ${pluginFile}`);

// Clean up the superseded plugin, both halves. An existing android/ (an
// in-place rebuild on a device that already had this plugin, rather than a
// fresh clone) has AllFilesAccessPlugin.java AND a
// registerPlugin(AllFilesAccessPlugin.class) line already sitting in
// MainActivity.java from before this migration. Deleting only the .java
// file and leaving the registration would break the very next build with
// "cannot find symbol: class AllFilesAccessPlugin" - the registration has
// to go too, in the same pass.
const oldPluginFile = path.join(javaDir, 'AllFilesAccessPlugin.java');
if (fs.existsSync(oldPluginFile)) {
  fs.unlinkSync(oldPluginFile);
  console.log(`Removed superseded ${oldPluginFile}`);
}

let mainActivity = fs.readFileSync(mainActivityFile, 'utf8');
const registrationLine = /^\s*registerPlugin\(AllFilesAccessPlugin\.class\);\s*\n/m;
if (registrationLine.test(mainActivity)) {
  mainActivity = mainActivity.replace(registrationLine, '');
  fs.writeFileSync(mainActivityFile, mainActivity);
  console.log('Removed superseded registerPlugin(AllFilesAccessPlugin.class) from MainActivity.java.');
}

const result = ensurePluginRegistered(mainActivity, 'DocumentPickerPlugin');
console.log(result.message);
if (result.changed) {
  fs.writeFileSync(mainActivityFile, result.content);
}
if (result.error) {
  process.exit(1);
}
