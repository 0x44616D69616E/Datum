package org.freemaps.datum;

import android.app.Activity;
import android.content.ActivityNotFoundException;
import android.content.ContentResolver;
import android.content.Intent;
import android.content.UriPermission;
import android.database.Cursor;
import android.net.Uri;
import android.os.Build;
import android.provider.DocumentsContract;
import android.provider.DocumentsContract.Document;
import android.provider.OpenableColumns;
import android.provider.Settings;

import androidx.activity.result.ActivityResult;

import com.getcapacitor.JSArray;
import com.getcapacitor.JSObject;
import com.getcapacitor.Plugin;
import com.getcapacitor.PluginCall;
import com.getcapacitor.PluginMethod;
import com.getcapacitor.annotation.ActivityCallback;
import com.getcapacitor.annotation.CapacitorPlugin;

import java.io.ByteArrayOutputStream;
import java.io.InputStream;
import java.io.OutputStream;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;

// Generated by scripts/ensure-document-picker-plugin.js - safe to
// regenerate, don't hand-edit (changes will be overwritten on the next
// sync).
@CapacitorPlugin(name = "DocumentPicker")
public class DocumentPickerPlugin extends Plugin {

    @PluginMethod
    public void pickFiles(PluginCall call) {
        Intent intent = new Intent(Intent.ACTION_OPEN_DOCUMENT);
        intent.addCategory(Intent.CATEGORY_OPENABLE);
        intent.putExtra(Intent.EXTRA_ALLOW_MULTIPLE, true);
        // GPX has no registered MIME type, and most file managers and mail
        // apps report it as application/octet-stream anyway - the manifest's
        // own GPX intent filter hits the identical problem (see
        // ensure-gpx-intent.js). "*/*" plus the .gpx filtering already done
        // on the JS side is the only reliable combination.
        intent.setType("*/*");
        startActivityForResult(call, intent, "pickFilesResult");
    }

    @ActivityCallback
    private void pickFilesResult(PluginCall call, ActivityResult result) {
        if (call == null) return;
        if (result.getResultCode() != Activity.RESULT_OK || result.getData() == null) {
            // Includes the user backing out with nothing selected - not an
            // error, just nothing picked.
            JSObject empty = new JSObject();
            empty.put("files", new JSArray());
            call.resolve(empty);
            return;
        }

        Intent data = result.getData();
        java.util.List<Uri> uris = new java.util.ArrayList<>();
        if (data.getClipData() != null) {
            // Multi-select result.
            int count = data.getClipData().getItemCount();
            for (int i = 0; i < count; i++) uris.add(data.getClipData().getItemAt(i).getUri());
        } else if (data.getData() != null) {
            // Single-select result.
            uris.add(data.getData());
        }

        JSArray files = new JSArray();
        for (Uri uri : uris) {
            try {
                String name = queryDisplayName(uri);
                String text = readUriAsText(uri);
                JSObject file = new JSObject();
                file.put("name", name);
                file.put("data", text);
                files.put(file);
            } catch (Exception e) {
                // One unreadable file (permission revoked mid-pick, a
                // provider hiccup) shouldn't fail the whole batch - the JS
                // side already handles a picked file that didn't come back.
            }
        }

        JSObject resultObj = new JSObject();
        resultObj.put("files", files);
        call.resolve(resultObj);
    }

    private String readUriAsText(Uri uri) throws Exception {
        InputStream in = getContext().getContentResolver().openInputStream(uri);
        if (in == null) throw new Exception("Could not open the selected file.");
        try {
            ByteArrayOutputStream buffer = new ByteArrayOutputStream();
            byte[] chunk = new byte[8192];
            int n;
            while ((n = in.read(chunk)) != -1) buffer.write(chunk, 0, n);
            return buffer.toString("UTF-8");
        } finally {
            in.close();
        }
    }

    private String queryDisplayName(Uri uri) {
        String name = "import.gpx";
        Cursor cursor = getContext().getContentResolver().query(uri, null, null, null, null);
        if (cursor != null) {
            try {
                int idx = cursor.getColumnIndex(OpenableColumns.DISPLAY_NAME);
                if (idx >= 0 && cursor.moveToFirst()) {
                    String n = cursor.getString(idx);
                    if (n != null && !n.isEmpty()) name = n;
                }
            } finally {
                cursor.close();
            }
        }
        return name;
    }

    // ---------- Storage folder (persisted tree grant) ----------
    //
    // NOTE for anyone editing this: the Java here lives inside a JS template
    // literal, so it must not contain backslashes or backticks. Messages use
    // single quotes for that reason.

    private static final String EXTERNAL_STORAGE_AUTHORITY = "com.android.externalstorage.documents";
    // Every file is created with this type. ExternalStorageProvider appends
    // an extension that matches a specific MIME type (text/plain would turn
    // track.gpx into track.gpx.txt); octet-stream keeps the name exactly.
    private static final String FILE_MIME = "application/octet-stream";

    @PluginMethod
    public void pickFolder(PluginCall call) {
        Intent intent = new Intent(Intent.ACTION_OPEN_DOCUMENT_TREE);
        intent.addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION
            | Intent.FLAG_GRANT_WRITE_URI_PERMISSION
            | Intent.FLAG_GRANT_PERSISTABLE_URI_PERMISSION
            | Intent.FLAG_GRANT_PREFIX_URI_PERMISSION);
        // Opens the picker somewhere sensible, e.g. Documents, so re-picking
        // an existing Documents/Datum folder is a tap or two. Only a hint:
        // the user can navigate anywhere. API 26+.
        String initial = call.getString("initialPath");
        if (initial != null && !initial.isEmpty() && Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) {
            intent.putExtra(DocumentsContract.EXTRA_INITIAL_URI,
                DocumentsContract.buildDocumentUri(EXTERNAL_STORAGE_AUTHORITY, "primary:" + initial));
        }
        try {
            startActivityForResult(call, intent, "pickFolderResult");
        } catch (ActivityNotFoundException e) {
            call.reject("This device has no system folder picker.");
        }
    }

    @ActivityCallback
    private void pickFolderResult(PluginCall call, ActivityResult result) {
        if (call == null) return;
        JSObject out = new JSObject();
        if (result.getResultCode() != Activity.RESULT_OK || result.getData() == null || result.getData().getData() == null) {
            // Backed out without choosing. Not an error; no treeUri in the result.
            call.resolve(out);
            return;
        }
        Uri tree = result.getData().getData();
        try {
            // Without this the grant ends when the app process does, and
            // every write after a restart would fail.
            getContext().getContentResolver().takePersistableUriPermission(tree,
                Intent.FLAG_GRANT_READ_URI_PERMISSION | Intent.FLAG_GRANT_WRITE_URI_PERMISSION);
        } catch (SecurityException e) {
            call.reject("Android did not grant lasting access to that folder: " + e.getMessage());
            return;
        }
        String rootId = DocumentsContract.getTreeDocumentId(tree);
        out.put("treeUri", tree.toString());
        out.put("name", queryDocumentName(tree, rootId));
        out.put("label", labelForDocumentId(rootId));
        call.resolve(out);
    }

    @PluginMethod
    public void hasFolderAccess(PluginCall call) {
        String s = call.getString("treeUri");
        boolean ok = false;
        if (s != null && !s.isEmpty()) {
            Uri tree = Uri.parse(s);
            for (UriPermission p : getContext().getContentResolver().getPersistedUriPermissions()) {
                if (p.getUri().equals(tree) && p.isReadPermission() && p.isWritePermission()) { ok = true; break; }
            }
        }
        JSObject out = new JSObject();
        out.put("granted", ok);
        call.resolve(out);
    }

    // Persisted grants are capped per app, so a folder Datum no longer uses
    // is handed back rather than left to accumulate.
    @PluginMethod
    public void releaseFolder(PluginCall call) {
        String s = call.getString("treeUri");
        if (s != null && !s.isEmpty()) {
            try {
                getContext().getContentResolver().releasePersistableUriPermission(Uri.parse(s),
                    Intent.FLAG_GRANT_READ_URI_PERMISSION | Intent.FLAG_GRANT_WRITE_URI_PERMISSION);
            } catch (SecurityException e) {
                // Already released, or never held. Nothing to undo.
            }
        }
        call.resolve();
    }

    @PluginMethod
    public void readdir(PluginCall call) {
        try {
            Uri tree = treeUri(call);
            List<String> segs = segments(call.getString("path"));
            String dirId = walkDirs(tree, segs, segs.size(), false);
            if (dirId == null) { call.reject("Folder does not exist: " + call.getString("path")); return; }
            JSArray files = new JSArray();
            Cursor c = queryChildren(tree, dirId);
            if (c != null) {
                try {
                    while (c.moveToNext()) {
                        JSObject f = new JSObject();
                        f.put("name", c.getString(1));
                        f.put("type", Document.MIME_TYPE_DIR.equals(c.getString(2)) ? "directory" : "file");
                        files.put(f);
                    }
                } finally {
                    c.close();
                }
            }
            JSObject out = new JSObject();
            out.put("files", files);
            call.resolve(out);
        } catch (Exception e) {
            call.reject(String.valueOf(e.getMessage()));
        }
    }

    // Creates every missing folder along the path. Succeeds quietly if it
    // already exists, so callers do not have to tell the two apart.
    @PluginMethod
    public void mkdir(PluginCall call) {
        try {
            Uri tree = treeUri(call);
            List<String> segs = segments(call.getString("path"));
            walkDirs(tree, segs, segs.size(), true);
            call.resolve();
        } catch (Exception e) {
            call.reject(String.valueOf(e.getMessage()));
        }
    }

    @PluginMethod
    public void readFile(PluginCall call) {
        try {
            Uri tree = treeUri(call);
            String[] child = findFile(tree, segments(call.getString("path")));
            if (child == null) { call.reject("File does not exist: " + call.getString("path")); return; }
            InputStream in = getContext().getContentResolver().openInputStream(
                DocumentsContract.buildDocumentUriUsingTree(tree, child[0]));
            if (in == null) { call.reject("Could not open " + call.getString("path")); return; }
            JSObject out = new JSObject();
            out.put("data", readStreamAsText(in));
            call.resolve(out);
        } catch (Exception e) {
            call.reject(String.valueOf(e.getMessage()));
        }
    }

    // Replaces the file if it exists, creates it (and any missing parent
    // folders) if not. Never creates a second copy: createDocument on an
    // existing name would make 'track (1).gpx' instead of overwriting.
    @PluginMethod
    public void writeFile(PluginCall call) {
        try {
            Uri tree = treeUri(call);
            List<String> segs = segments(call.getString("path"));
            if (segs.isEmpty()) { call.reject("No file name given."); return; }
            String name = segs.get(segs.size() - 1);
            String parentId = walkDirs(tree, segs, segs.size() - 1, true);
            byte[] bytes = call.getString("data", "").getBytes(StandardCharsets.UTF_8);
            ContentResolver resolver = getContext().getContentResolver();
            String[] existing = findChild(tree, parentId, name);
            if (existing != null && Document.MIME_TYPE_DIR.equals(existing[1])) {
                call.reject("'" + name + "' is a folder, not a file.");
                return;
            }
            Uri doc;
            if (existing != null) {
                doc = DocumentsContract.buildDocumentUriUsingTree(tree, existing[0]);
            } else {
                doc = DocumentsContract.createDocument(resolver,
                    DocumentsContract.buildDocumentUriUsingTree(tree, parentId), FILE_MIME, name);
                if (doc == null) { call.reject("Could not create " + call.getString("path")); return; }
            }
            OutputStream os;
            try {
                // "wt" truncates. Plain "w" does not on every provider, and
                // overwriting a longer file with a shorter one would leave
                // the old tail behind as corrupt trailing XML.
                os = resolver.openOutputStream(doc, "wt");
            } catch (Exception notSupported) {
                // A provider without "wt": start from an empty file instead.
                DocumentsContract.deleteDocument(resolver, doc);
                doc = DocumentsContract.createDocument(resolver,
                    DocumentsContract.buildDocumentUriUsingTree(tree, parentId), FILE_MIME, name);
                if (doc == null) { call.reject("Could not recreate " + call.getString("path")); return; }
                os = resolver.openOutputStream(doc, "w");
            }
            if (os == null) { call.reject("Could not open " + call.getString("path") + " for writing."); return; }
            try {
                os.write(bytes);
            } finally {
                os.close();
            }
            call.resolve();
        } catch (Exception e) {
            call.reject(String.valueOf(e.getMessage()));
        }
    }

    // Deletes a file, or a folder and everything in it. Refuses an empty
    // path: that would be the picked folder itself, which Datum never
    // deletes. This is a second gate behind the JS-side guards in storage.js.
    @PluginMethod
    public void deleteFile(PluginCall call) {
        try {
            Uri tree = treeUri(call);
            List<String> segs = segments(call.getString("path"));
            if (segs.isEmpty()) { call.reject("Refusing to delete the chosen storage folder itself."); return; }
            String[] target = findFile(tree, segs);
            if (target == null) { call.reject("Does not exist: " + call.getString("path")); return; }
            boolean ok = DocumentsContract.deleteDocument(getContext().getContentResolver(),
                DocumentsContract.buildDocumentUriUsingTree(tree, target[0]));
            if (!ok) { call.reject("Could not delete " + call.getString("path")); return; }
            call.resolve();
        } catch (Exception e) {
            call.reject(String.valueOf(e.getMessage()));
        }
    }

    private Uri treeUri(PluginCall call) throws Exception {
        String s = call.getString("treeUri");
        if (s == null || s.isEmpty()) throw new Exception("No storage folder has been chosen.");
        return Uri.parse(s);
    }

    // Paths address documents by display name, one level at a time, so ".."
    // could never actually climb out of the grant. Rejected anyway: a path
    // containing it is a bug on the JS side and should fail loudly.
    private List<String> segments(String path) throws Exception {
        List<String> out = new ArrayList<>();
        if (path == null) return out;
        for (String seg : path.split("/")) {
            if (seg.isEmpty()) continue;
            if (seg.equals(".") || seg.equals("..")) throw new Exception("Refusing a path containing '" + seg + "': " + path);
            out.add(seg);
        }
        return out;
    }

    private Cursor queryChildren(Uri tree, String parentId) {
        return getContext().getContentResolver().query(
            DocumentsContract.buildChildDocumentsUriUsingTree(tree, parentId),
            new String[] { Document.COLUMN_DOCUMENT_ID, Document.COLUMN_DISPLAY_NAME, Document.COLUMN_MIME_TYPE },
            null, null, null);
    }

    // Returns { documentId, mimeType } for the named child, or null. Providers
    // ignore query selections for child listings, so this has to scan.
    private String[] findChild(Uri tree, String parentId, String name) {
        Cursor c = queryChildren(tree, parentId);
        if (c == null) return null;
        try {
            while (c.moveToNext()) {
                if (name.equals(c.getString(1))) return new String[] { c.getString(0), c.getString(2) };
            }
        } finally {
            c.close();
        }
        return null;
    }

    // Walks the first 'count' segments as folders from the picked folder,
    // creating missing ones if asked. Returns the last folder's document id,
    // or null if a folder is missing and create is false.
    private String walkDirs(Uri tree, List<String> segs, int count, boolean create) throws Exception {
        String id = DocumentsContract.getTreeDocumentId(tree);
        ContentResolver resolver = getContext().getContentResolver();
        for (int i = 0; i < count; i++) {
            String name = segs.get(i);
            String[] child = findChild(tree, id, name);
            if (child == null) {
                if (!create) return null;
                Uri made = DocumentsContract.createDocument(resolver,
                    DocumentsContract.buildDocumentUriUsingTree(tree, id), Document.MIME_TYPE_DIR, name);
                if (made == null) throw new Exception("Could not create folder '" + name + "'.");
                id = DocumentsContract.getDocumentId(made);
            } else {
                if (!Document.MIME_TYPE_DIR.equals(child[1])) throw new Exception("'" + name + "' is a file, not a folder.");
                id = child[0];
            }
        }
        return id;
    }

    // The last segment as a file or folder, or null if anything is missing.
    private String[] findFile(Uri tree, List<String> segs) throws Exception {
        if (segs.isEmpty()) return null;
        String parentId = walkDirs(tree, segs, segs.size() - 1, false);
        if (parentId == null) return null;
        return findChild(tree, parentId, segs.get(segs.size() - 1));
    }

    private String queryDocumentName(Uri tree, String docId) {
        String name = "";
        Cursor c = getContext().getContentResolver().query(
            DocumentsContract.buildDocumentUriUsingTree(tree, docId),
            new String[] { Document.COLUMN_DISPLAY_NAME }, null, null, null);
        if (c != null) {
            try {
                if (c.moveToFirst() && c.getString(0) != null) name = c.getString(0);
            } finally {
                c.close();
            }
        }
        return name;
    }

    // "primary:Documents/Datum" -> "Documents/Datum". Other volumes (an SD
    // card shows up as e.g. "1A2B-3C4D:Maps") are labelled as the SD card.
    private String labelForDocumentId(String docId) {
        int colon = docId.indexOf(':');
        String volume = colon >= 0 ? docId.substring(0, colon) : "";
        String rel = colon >= 0 ? docId.substring(colon + 1) : docId;
        String base = "primary".equals(volume) ? "" : "SD card";
        if (rel.isEmpty()) return base.isEmpty() ? "Internal storage" : base;
        return base.isEmpty() ? rel : base + "/" + rel;
    }

    private String readStreamAsText(InputStream in) throws Exception {
        try {
            ByteArrayOutputStream buffer = new ByteArrayOutputStream();
            byte[] chunk = new byte[8192];
            int n;
            while ((n = in.read(chunk)) != -1) buffer.write(chunk, 0, n);
            return buffer.toString("UTF-8");
        } finally {
            in.close();
        }
    }

    @PluginMethod
    public void openAppSettings(PluginCall call) {
        Intent intent = new Intent(Settings.ACTION_APPLICATION_DETAILS_SETTINGS);
        intent.setData(Uri.parse("package:" + getContext().getPackageName()));
        getActivity().startActivity(intent);
        call.resolve();
    }
}
