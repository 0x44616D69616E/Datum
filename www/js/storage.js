// storage.js
//
// Handles the on-device "storage folder" setup and export/import of all
// app data. Two different kinds of storage are deliberately kept separate
// here, and it's worth being upfront about the distinction:
//
// 1. LIVE data (map tiles, flags, routes, tracks, sessions, layer presets,
//    settings) stays in IndexedDB/localStorage, which is what the browser
//    engine actually needs for fast reads while the map is in active use.
//    Map tiles alone can be hundreds of MB - that's not something a plain
//    text/JSON file store could handle responsively.
// 2. This module adds an EXPORT/BACKUP path on top of that: writing a
//    single JSON snapshot of everything except the map tiles themselves
//    (which stay cached from their original re-downloadable sources) to a
//    real file in the folder the user chooses, and reading it back in.
//    That's what "setting up storage" means in Settings - establishing
//    where backups go, not relocating the live app data itself.

import * as Store from './dataStore.js';

let CapFilesystem = null;
let CapDocumentPicker = null;
try {
  // eslint-disable-next-line no-undef
  CapFilesystem = Capacitor?.Plugins?.Filesystem || null;
  // eslint-disable-next-line no-undef
  CapDocumentPicker = Capacitor?.Plugins?.DocumentPicker || null;
} catch (e) {
  CapFilesystem = null;
  CapDocumentPicker = null;
}

// Renamed from 'Cairn' in the Datum rebrand. NOTE: this changes where
// backups are written. Anyone who already had backups in a "Cairn" folder
// will still have them - untouched, on disk - but the app will now look in
// "Datum" and won't list them. Moving the old files across (or re-picking
// the folder) is the migration.
export const STORAGE_DIR = 'Datum'; // subfolder created under wherever the user picks

// Storage is reached through the folder grant, so the native folder plugin is
// what has to be present. Capacitor Filesystem is still used only to read a
// file another app hands Datum (readExternalFile).
export function isFilesystemAvailable() {
  return !!CapDocumentPicker;
}

// ---------- Document picker (Storage Access Framework) ----------
// Replaces the old "All files access" (MANAGE_EXTERNAL_STORAGE) based
// folder browser and file browser. A GPX import is exactly what Android's
// own system document picker is for: one or more files the user explicitly
// chose, read through the ContentResolver, with no broad storage
// permission declared or requested at all. The storage folder below uses the
// same framework, through a folder grant instead of a single-file one.
export function isDocumentPickerAvailable() {
  return !!CapDocumentPicker;
}

// Returns an array of { name, data } - one per file the user picked. The
// native side allows multi-select, so "pick one file" and "pick several to
// import at once" are the same call; a single-element array just means they
// tapped one file.
export async function pickGpxFiles() {
  if (!CapDocumentPicker) throw new Error('Document picker plugin not available - run "npm run fix-manifest" and rebuild.');
  const res = await CapDocumentPicker.pickFiles();
  return res.files || [];
}

// Opens the system "App info" settings screen for Datum, so a user whose
// storage writes are failing (permission revoked some other way, an
// unusual device policy, etc.) has somewhere to go. Not tied to any one
// permission - unlike the old All Files Access shortcut, this is a generic
// escape hatch now that nothing in the app requests a special permission.
export async function openAppSettings() {
  if (!CapDocumentPicker) throw new Error('Plugin not available - run "npm run fix-manifest" and rebuild.');
  await CapDocumentPicker.openAppSettings();
}

// ---------- Storage folder (Storage Access Framework) ----------
// The storage folder is one the user picks with Android's own folder picker.
// Android then grants Datum lasting read and write access to that folder and
// everything in it, and every file operation in this module goes through that
// grant (see DocumentPickerPlugin, generated by
// scripts/ensure-document-picker-plugin.js). No storage permission is declared
// or requested.
//
// This replaced writing to Documents/Datum or Download/Datum by raw file path,
// which broke once MANAGE_EXTERNAL_STORAGE was removed in 1.6.10: without it,
// Android only lets an app change files that the same installation created.
// Shared storage outlives an uninstall but the record of who created each file
// does not, so a Datum folder left by any earlier install (including the 1.6.3
// switch from the debug key to the release key, which forced a reinstall)
// became read-only to Datum, and setup failed while Download, a fresh folder,
// worked. A folder grant covers every file in the folder regardless of who
// created it.
//
// Datum works in a "Datum" subfolder of whatever is picked, unless the picked
// folder is itself called Datum, in which case it is used directly. Re-picking
// an existing Documents/Datum after updating therefore carries on exactly
// where the previous version left off.

const TREE_URI_KEY = 'storageTreeUri';
const TREE_NAME_KEY = 'storageTreeName';
const TREE_LABEL_KEY = 'storageTreeLabel';
const TREE_IS_DATUM_KEY = 'storageTreeIsDatum';
// Written by 1.6.10 and earlier, which addressed storage by raw path. Only
// read now to tell an upgrading user why they need to choose their folder
// again; never used to build a path.
const OLD_DIRECTORY_KEY = 'storageDirectory';
const OLD_RELATIVE_PATH_KEY = 'storageRelativePath';

function treeUri() {
  return localStorage.getItem(TREE_URI_KEY) || '';
}

// Paths are relative to the picked folder, joined with "/". Empty parts are
// dropped, so a Datum root of '' (the picked folder is Datum itself) joins
// cleanly instead of producing a leading slash.
function joinPath(...parts) {
  return parts.filter(Boolean).join('/');
}

// The Datum folder, relative to the picked folder.
function datumRoot() {
  return localStorage.getItem(TREE_IS_DATUM_KEY) === 'true' ? '' : STORAGE_DIR;
}

// Thin adapter over the native folder operations. Every read and write in
// this module goes through these five, so nothing else needs to know how the
// folder is reached.
async function fsCall(method, args) {
  if (!CapDocumentPicker) throw new Error('Storage plugin not available - run "npm run fix-manifest" and rebuild.');
  const uri = treeUri();
  if (!uri) throw new Error('No storage folder has been chosen.');
  return CapDocumentPicker[method]({ treeUri: uri, ...args });
}
async function fsMkdir(path) { await fsCall('mkdir', { path }); }
async function fsReaddir(path) { return (await fsCall('readdir', { path })).files || []; }
async function fsReadFile(path) { return (await fsCall('readFile', { path })).data; }
async function fsWriteFile(path, data) { await fsCall('writeFile', { path, data }); }
async function fsDelete(path) { await fsCall('deleteFile', { path }); }

