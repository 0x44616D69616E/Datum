// Creates the Datum folder if needed and writes the marker README, which also
// proves the folder is writable before Datum relies on it.
async function writeReadme() {
  await fsMkdir(datumRoot());
  await fsWriteFile(joinPath(datumRoot(), 'README.txt'), README_TEXT);
}

const TREE_KEYS = [TREE_URI_KEY, TREE_NAME_KEY, TREE_LABEL_KEY, TREE_IS_DATUM_KEY];

// Opens Android's folder picker and makes the chosen folder Datum's storage.
// Returns the location label, or null if the user backed out.
//
// The new folder has to accept a write before it replaces the old one, and the
// old folder's grant is only released after that, so a failed switch leaves
// storage exactly as it was.
export async function chooseStorageFolder() {
  if (!CapDocumentPicker) throw new Error('Storage plugin not available - run "npm run fix-manifest" and rebuild.');
  const picked = await CapDocumentPicker.pickFolder({ initialPath: 'Documents' });
  if (!picked || !picked.treeUri) return null;

  const previous = {};
  for (const k of TREE_KEYS) previous[k] = localStorage.getItem(k);
  const previousConfigured = localStorage.getItem('storageConfigured');

  localStorage.setItem(TREE_URI_KEY, picked.treeUri);
  localStorage.setItem(TREE_NAME_KEY, picked.name || '');
  localStorage.setItem(TREE_LABEL_KEY, picked.label || picked.name || 'the chosen folder');
  localStorage.setItem(TREE_IS_DATUM_KEY, picked.name === STORAGE_DIR ? 'true' : 'false');
  try {
    await writeReadme();
  } catch (e) {
    for (const k of TREE_KEYS) {
      if (previous[k] === null) localStorage.removeItem(k);
      else localStorage.setItem(k, previous[k]);
    }
    if (previousConfigured === null) localStorage.removeItem('storageConfigured');
    else localStorage.setItem('storageConfigured', previousConfigured);
    if (picked.treeUri !== previous[TREE_URI_KEY]) {
      try { await CapDocumentPicker.releaseFolder({ treeUri: picked.treeUri }); } catch (_) { /* nothing held */ }
    }
    throw new Error(`Could not write to that folder: ${e.message}`);
  }

  localStorage.setItem('storageConfigured', 'true');
  localStorage.removeItem(OLD_DIRECTORY_KEY);
  localStorage.removeItem(OLD_RELATIVE_PATH_KEY);
  const oldUri = previous[TREE_URI_KEY];
  if (oldUri && oldUri !== picked.treeUri) {
    try { await CapDocumentPicker.releaseFolder({ treeUri: oldUri }); } catch (_) { /* already gone */ }
  }
  return getConfiguredPathLabel();
}

// True for someone upgrading from 1.6.10 or earlier who had storage set up the
// old way and has not chosen a folder since. Their files are untouched on disk;
// Datum just needs the folder chosen once through the picker.
export function needsFolderRepick() {
  return !treeUri() && !!localStorage.getItem(OLD_DIRECTORY_KEY);
}

// Where the files are, as the user would find them in a file manager.
export function getConfiguredPathLabel() {
  if (!isStorageConfigured()) return null;
  const label = localStorage.getItem(TREE_LABEL_KEY) || 'the chosen folder';
  return datumRoot() ? `${label}/${STORAGE_DIR}` : label;
}

// Configured means a folder has been chosen through the picker. A leftover
// "storageConfigured" from the raw-path versions does not count, since there
// is no grant behind it.
export function isStorageConfigured() {
  return localStorage.getItem('storageConfigured') === 'true' && !!treeUri();
}

// Whether Android still holds Datum's grant on the folder. The user can revoke
// it from system settings, and clearing app data drops it too.
export async function hasFolderAccess() {
  if (!CapDocumentPicker || !treeUri()) return false;
  try {
    return !!(await CapDocumentPicker.hasFolderAccess({ treeUri: treeUri() })).granted;
  } catch (e) {
    return false;
  }
}

async function gatherAllData() {
  const [waypoints, routes, tracks, sessions] = await Promise.all([
    Store.getWaypoints(), Store.getRoutes(), Store.getTracks(), Store.getSessions()
  ]);
  return {
    exportedAt: new Date().toISOString(),
    waypoints, routes, tracks, sessions,
    layerStack: JSON.parse(localStorage.getItem('layerStack') || 'null'),
    layerPresets: JSON.parse(localStorage.getItem('layerPresets') || '[]'),
    savedRegions: JSON.parse(localStorage.getItem('savedRegions') || '[]'),
    debugMode: localStorage.getItem('debugMode') === 'true'
  };
}

// Folder layout under the user's chosen directory.
//
//   Datum/
//     current/                 the live, unsaved session
//       waypoints/ routes/ tracks/
//     sessions/<session-id>/   one folder per saved session
//       waypoints/ routes/ tracks/
//     presets/                 layer presets (.datum-preset.json, Datum only)
//     exports/                 packaged single-file session exports (.gpx)
//     backups/                 whole-app JSON
//
// Folder names use GPX's own vocabulary, so waypoints/ rather than flags/: a
// Datum flag and a GPX <wpt> are the same record, and a folder name that
// disagrees with the file contents helps nobody.
export const RECORD_FOLDERS = ['waypoints', 'routes', 'tracks'];

export const SHARE_FOLDERS = {
  current: 'current',
  sessions: 'sessions',
  presets: 'presets',
  backups: 'backups'
};

// Written by the earlier flat layout and no longer used. Records now live only
// under current/ or a session folder, so these are stale duplicates rather
// than a second home for anything. Listed so they can be found and cleaned up
// deliberately, never deleted silently: they still contain real data.
export const LEGACY_FOLDERS = ['flags', 'routes', 'tracks', 'exports'];

// Counts what is left behind by the old layout, including loose .gpx files
// sitting directly in sessions/ rather than inside a session folder.
export async function findLegacyLeftovers() {
  if (!CapDocumentPicker || !isStorageConfigured()) return { folders: [], looseSessionFiles: [], total: 0 };
  const root = datumRoot();
  const folders = [];
  for (const name of LEGACY_FOLDERS) {
    const count = await countFilesUnder(joinPath(root, name));
    if (count) folders.push({ name, count });
  }
  // A packaged session export used to be written straight into sessions/,
  // where it sits confusingly beside the session folders themselves.
  const looseSessionFiles = [];
  for (const entry of await listDirEntries(joinPath(root, SHARE_FOLDERS.sessions))) {
    const name = entry.name || entry;
    if ((entry.type || '') !== 'directory' && /\.gpx$/i.test(name)) looseSessionFiles.push(name);
  }
  const total = folders.reduce((n, f) => n + f.count, 0) + looseSessionFiles.length;
  return { folders, looseSessionFiles, total };
}

export async function removeLegacyLeftovers() {
  if (!CapDocumentPicker || !isStorageConfigured()) return 0;
  const root = datumRoot();
  let removed = 0;
  for (const name of LEGACY_FOLDERS) {
    const count = await countFilesUnder(joinPath(root, name));
    if (!count) continue;
    await deleteTreeUnchecked(joinPath(root, name));
    removed += count;
  }
  for (const entry of await listDirEntries(joinPath(root, SHARE_FOLDERS.sessions))) {
    const name = entry.name || entry;
    if ((entry.type || '') === 'directory' || !/\.gpx$/i.test(name)) continue;
    try {
      await fsDelete(joinPath(root, SHARE_FOLDERS.sessions, name));
      removed++;
    } catch (e) { /* already gone */ }
  }
  return removed;
}

function shareDir(kind) {
  return joinPath(datumRoot(), SHARE_FOLDERS[kind]);
}

async function ensureDir(path) {
  // Native mkdir creates every missing folder and succeeds quietly when the
  // folder already exists, so the only failures left are real ones
  // (grant revoked, storage unmounted, disk full, the folder deleted out from
  // under the app). Those must not be swallowed: the write that follows would
  // fail into the same silence and an export would report success having
  // written nothing.
  try {
    await fsMkdir(path);
  } catch (e) {
    throw new Error(`Could not create folder "${path}": ${String(e && e.message || e)}`);
  }
}

// Freeform user text becomes a filename. Beyond path separators, Android's
// FAT-derived external storage rejects several characters outright, and a name
// that is empty after stripping would produce a hidden dotfile.
// Session ids reach the filesystem as directory names, so they are validated
// rather than trusted. This is the single gate every destructive path goes
// through; see deleteSessionFolder for why that matters.
const SAFE_ID = /^[A-Za-z0-9][A-Za-z0-9._-]{3,80}$/;
export function isSafeSessionId(id) {
  return typeof id === 'string' && SAFE_ID.test(id) && !id.includes('..');
}

// Sortable and readable: 20260811T134549-pusch-ridge. Sorts chronologically in
// any file manager and says what it is without being opened. The slug comes
// from the name at creation time and is never recomputed, because renaming
// must not move a directory.
export function makeSessionId(name) {
  const ts = new Date().toISOString().replace(/[-:]/g, '').replace(/\..+$/, '');
  const slug = String(name || '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 40);
  return slug ? `${ts}-${slug}` : ts;
}

export function currentDir() {
  return joinPath(datumRoot(), SHARE_FOLDERS.current);
}
export function sessionDir(id) {
  if (!isSafeSessionId(id)) throw new Error(`Refusing to build a path from an unsafe session id: ${JSON.stringify(id)}`);
  return joinPath(datumRoot(), SHARE_FOLDERS.sessions, id);
}

// Creates the waypoints/routes/tracks trio inside a session or current folder.
export async function ensureRecordFolders(baseDir) {
  for (const f of RECORD_FOLDERS) await ensureDir(joinPath(baseDir, f));
}

// ---------------------------------------------------------------------------
// Deletion. Treat everything below as the highest-risk code in the app.
// ---------------------------------------------------------------------------
//
// Deleting a session removes a directory tree from external storage, and a
// session folder is frequently the only remaining copy of an old trip. The
// failure that matters is not an error, it is a path that silently resolves
// one level too high: if an id were ever empty or malformed, a naive join
// would produce ".../sessions/" and take every session with it.
//
// Hence the id is validated against a strict pattern, the resolved path is
// re-checked to sit strictly inside the sessions folder, and the delete
// refuses rather than guessing. sessionDir() throws on a bad id before a path
// is even built, so this is a second gate rather than the only one.

async function listDirEntries(path) {
  try {
    return await fsReaddir(path);
  } catch (e) {
    return [];
  }
}

// Counts what a delete would remove, so a confirmation can state it rather
// than asking the user to approve an unknown quantity.
export async function countFilesUnder(path) {
  if (!CapDocumentPicker || !isStorageConfigured()) return 0;
  let total = 0;
  for (const entry of await listDirEntries(path)) {
    const name = entry.name || entry;
    if ((entry.type || '') === 'directory') total += await countFilesUnder(joinPath(path, name));
    else total++;
  }
  return total;
}

// Deleting a folder through the grant removes everything in it, so this is one
// call rather than a walk. An empty path would be the picked folder itself,
// which Datum never deletes; the native side refuses that too, as a second
// gate.
async function deleteTreeUnchecked(path) {
  if (!path) return;
  try {
    await fsDelete(path);
  } catch (e) { /* already gone */ }
}

export async function deleteSessionFolder(id) {
  if (!CapDocumentPicker || !isStorageConfigured()) return false;
  // Gate one: the id itself. Never derived from a display name, which is
  // freeform user text and could contain anything.
  if (!isSafeSessionId(id)) {
    throw new Error(`Refusing to delete: unsafe session id ${JSON.stringify(id)}`);
  }
  const root = joinPath(datumRoot(), SHARE_FOLDERS.sessions);
  const target = joinPath(root, id);
  // Gate two: the resolved path must sit strictly inside the sessions folder
  // with a single non-empty final segment. This catches a malformed root as
  // well as a malformed id.
  const finalSegment = target.slice(root.length + 1);
  if (!target.startsWith(`${root}/`) || !finalSegment || finalSegment.includes('/')) {
    throw new Error(`Refusing to delete: "${target}" is not a single session folder`);
  }
  await deleteTreeUnchecked(target);
  return true;
}

// Removes everything under the Datum folder, including the folder itself.
//
// This is the most destructive filesystem operation in the app, and its risk
// profile is different from the session delete: there the danger was a
// malformed id resolving one level too high, here the target IS the top level,
// so the guard has to be that the target really is the Datum folder and never
// the folder the user picked to hold it.
//
// Two shapes, because the picked folder can be the Datum folder itself:
//   - Datum is a subfolder of the picked folder: delete that subfolder, and
//     only if it is exactly STORAGE_DIR.
//   - The picked folder is named Datum: delete what is inside it but keep the
//     folder, since it is the one Datum's grant covers. Re-checked against the
//     name Android reported at pick time, so this branch can never empty some
//     other folder.
export async function deleteEverything() {
  if (!CapDocumentPicker || !isStorageConfigured()) return 0;
  const dir = datumRoot();
  if (dir === '') {
    if (localStorage.getItem(TREE_NAME_KEY) !== STORAGE_DIR) {
      throw new Error('Refusing to delete: the chosen folder is not the Datum folder');
    }
    const count = await countFilesUnder('');
    for (const entry of await listDirEntries('')) await deleteTreeUnchecked(entry.name || entry);
    return count;
  }
  if (dir !== STORAGE_DIR) {
    throw new Error(`Refusing to delete: "${dir}" is not the Datum folder`);
  }
  const count = await countFilesUnder(dir);
  await deleteTreeUnchecked(dir);
  return count;
}

// Counts what deleteEverything would remove, so the confirmation can state it.
export async function countEverything() {
  if (!CapDocumentPicker || !isStorageConfigured()) return { files: 0, sessions: 0 };
  return { files: await countFilesUnder(datumRoot()), sessions: (await listSessionFolders()).length };
}

// Every settings and metadata key the app writes. Listed explicitly rather
// than clearing localStorage wholesale, because that would also wipe anything
// the WebView or a future library stores under its own keys, which is not
// ours to delete.
export const SETTINGS_KEYS = [
  'glassTheme', 'useMetricUnits', 'leftHanded', 'showCompassRibbon',
  'hideScaleBar', 'persistentRecord', 'debugMode', 'onboardingSeen',
  'compassNorthOffset', 'layerStack', 'layerPresets', 'savedRegions',
  'shareIncludeTimestamps', 'shareTrimEnabled', 'shareTrimStartMetres',
  'shareTrimEndMetres', 'mirrorPending',
  // Storage configuration goes last conceptually: clearing it returns the app
  // to its first-run state, which is the point of a full wipe.
  'storageConfigured', 'storageTreeUri', 'storageTreeName', 'storageTreeLabel',
  'storageTreeIsDatum', 'storageDirectory', 'storageRelativePath', 'storageRepickPrompted'
];

export function clearAllSettings() {
  // Hand back the folder grant as well, or a full wipe would leave Android
  // still listing Datum as having access to the folder.
  const uri = treeUri();
  if (uri && CapDocumentPicker) CapDocumentPicker.releaseFolder({ treeUri: uri }).catch(() => {});
  for (const k of SETTINGS_KEYS) localStorage.removeItem(k);
}

// Empties the live session folder without removing it. Deliberately a separate
// function from the session delete path so the two cannot be confused at a
// call site.
export async function clearCurrentFolder() {
  if (!CapDocumentPicker || !isStorageConfigured()) return;
  const dir = currentDir();
  for (const folder of RECORD_FOLDERS) await deleteTreeUnchecked(joinPath(dir, folder));
  await ensureRecordFolders(dir);
}

// Writes one record file into current/ or a session folder.
export async function writeRecordFile(baseDir, folder, filename, text) {
  if (!CapDocumentPicker || !isStorageConfigured()) return null;
  await ensureDir(joinPath(baseDir, folder));
  await fsWriteFile(joinPath(baseDir, folder, filename), text);
  return filename;
}

export async function readRecordFile(baseDir, folder, filename) {
  if (!CapDocumentPicker || !isStorageConfigured()) throw new Error('Storage folder is not configured.');
  return fsReadFile(joinPath(baseDir, folder, filename));
}

export async function listRecordFiles(baseDir, folder, extension) {
  if (!CapDocumentPicker || !isStorageConfigured()) return [];
  return (await listDirEntries(joinPath(baseDir, folder)))
    .filter(e => (e.type || '') !== 'directory')
    .map(e => e.name || e)
    .filter(n => !extension || n.endsWith(extension))
    .sort();
}

// The names of every saved session folder, used to find files to import.
// Anything that is not a valid session id is skipped rather than trusted,
// since these names feed straight back into path building.
export async function listSessionFolders() {
  if (!CapDocumentPicker || !isStorageConfigured()) return [];
  return (await listDirEntries(joinPath(datumRoot(), SHARE_FOLDERS.sessions)))
    .filter(e => (e.type || '') === 'directory')
    .map(e => e.name || e)
    .filter(isSafeSessionId);
}

// The packaged single-file export, written inside the session's own folder
// rather than loose in sessions/ where it sat confusingly beside the folders.
export async function writeSessionPackage(sessionDirPath, filename, text) {
  if (!CapDocumentPicker || !isStorageConfigured()) return null;
  await fsWriteFile(joinPath(sessionDirPath, filename), text);
  return filename;
}

export async function deleteRecordFile(baseDir, folder, filename) {
  if (!CapDocumentPicker || !isStorageConfigured()) return;
  try {
    await fsDelete(joinPath(baseDir, folder, filename));
  } catch (e) { /* already gone */ }
}

export function safeFilename(name, extension) {
  const safe = String(name)
    .replace(/[\/\\:*?"<>|]/g, '-')
    // eslint-disable-next-line no-control-regex
    .replace(/[\x00-\x1f]/g, '')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/^\.+/, '')
    .slice(0, 80);
  return `${safe || 'untitled'}${extension}`;
}

// Returns the filename written, or null when storage is not configured, which
// callers treat as "skip quietly" rather than as an error.
export async function writeShareFile(kind, filename, text) {
  if (!CapDocumentPicker || !isStorageConfigured()) return null;
  const dir = shareDir(kind);
  await ensureDir(dir);
  await fsWriteFile(joinPath(dir, filename), text);
  return filename;
}

export async function deleteShareFile(kind, filename) {
  if (!CapDocumentPicker || !isStorageConfigured()) return;
  try {
    await fsDelete(joinPath(shareDir(kind), filename));
  } catch (e) {
    // Already gone, or never written because storage was configured after the
    // record was created. Not worth surfacing.
  }
}

export async function listShareFiles(kind, extension) {
  if (!CapDocumentPicker || !isStorageConfigured()) return [];
  try {
    return (await fsReaddir(shareDir(kind)))
      .filter(f => (f.type || '') !== 'directory')
      .map(f => f.name)
      .filter(n => !extension || n.endsWith(extension))
      .sort();
  } catch (e) {
    return [];
  }
}

export async function readShareFile(kind, filename) {
  if (!CapDocumentPicker || !isStorageConfigured()) throw new Error('Storage folder is not configured.');
  return fsReadFile(joinPath(shareDir(kind), filename));
}

export const PRESET_EXTENSION = '.datum-preset.json';

export async function writePresetFile(preset) {
  const filename = safeFilename(preset.name, PRESET_EXTENSION);
  // Self-describing on purpose: a shared file lands in someone else's
  // Downloads with no context, so it states what it is and which schema it
  // follows rather than being a bare array.
  return writeShareFile('presets', filename, JSON.stringify({
    format: 'datum-layer-preset',
    version: 1,
    name: preset.name,
    savedAt: new Date().toISOString(),
    stack: preset.stack
  }, null, 2));
}

export async function deletePresetFile(name) {
  return deleteShareFile('presets', safeFilename(name, PRESET_EXTENSION));
}

// Malformed or foreign files are skipped rather than aborting the scan: these
// files arrive from other people, so one bad file must not block the rest.
export async function readPresetFiles() {
  const files = await listShareFiles('presets', '.json');
  const presets = [];
  const skipped = [];
  for (const filename of files) {
    try {
      const parsed = JSON.parse(await readShareFile('presets', filename));
      if (parsed.format !== 'datum-layer-preset' || !Array.isArray(parsed.stack)) {
        skipped.push(filename);
        continue;
      }
      presets.push({
        name: typeof parsed.name === 'string' && parsed.name.trim()
          ? parsed.name
          : filename.replace(PRESET_EXTENSION, ''),
        stack: parsed.stack
      });
    } catch (e) {
      skipped.push(filename);
    }
  }
  return { presets, skipped };
}

// Reads a file Android handed us from outside the app, via the URI in a VIEW
// intent. Kept here rather than in share.js because it is a storage concern:
// the URI is usually a content:// reference owned by another app's provider,
// not a path inside Datum's own folders.
export async function readExternalFile(uri) {
  if (!CapFilesystem) throw new Error('Filesystem access is not available in this environment.');
  // No `directory` argument. That parameter resolves a path relative to one of
  // Capacitor's known roots, which is exactly wrong for an absolute URI owned
  // by someone else; passing it would send the read looking inside Datum's
  // own storage for a file that is not there.
  const res = await CapFilesystem.readFile({ path: uri, encoding: 'utf8' });
  return res.data;
}

// Copies text into one of Datum's own folders, used after importing a file
// from outside so the mirror stays complete and the same file does not have to
// be found again.
export async function adoptExternalFile(kind, filename, text) {
  return writeShareFile(kind, filename, text);
}

// Makes sure there is a working storage folder before a write.
//
// Before 1.6.11 this silently configured Documents/Datum as a default, because
// an unconfigured folder made every export quietly do nothing. A folder grant
// cannot be given silently: the user has to pick the folder. So this opens the
// picker, but only when the caller passes { prompt: true }, meaning the user
// just asked for a storage action (sync, retry, package a session). Callers
// writing a best-effort side copy (a preset's shareable file, the mirror after
// saving a session) leave it off: a system picker appearing during something
// unrelated would be baffling. Those callers already report "no storage
// folder is set" when a write returns null.
//
// Returns true if it had to create or recreate the folder.
export async function ensureStorageRoot({ prompt = false } = {}) {
  if (!CapDocumentPicker) return false;
  if (!isStorageConfigured()) {
    if (!prompt) return false;
    const label = await chooseStorageFolder();
    if (!label) throw new Error('No storage folder chosen.');
    return true;
  }
  try {
    await fsReaddir(datumRoot());
    return false;
  } catch (e) {
    // The Datum folder was deleted from a file manager since setup. Recreated
    // here; if the grant itself is gone this fails loudly instead, which is
    // what the storage alert needs to show.
    await writeReadme();
    return true;
  }
}

export async function exportAllData() {
  if (!CapDocumentPicker || !isStorageConfigured()) throw new Error('No storage folder has been chosen.');
  await ensureDir(shareDir('backups'));
  const data = await gatherAllData();
  const filename = `datum-backup-${new Date().toISOString().replace(/[:.]/g, '-')}.json`;
  await fsWriteFile(joinPath(shareDir('backups'), filename), JSON.stringify(data, null, 2));
  return filename;
}

export async function importAllData(filename) {
  if (!CapDocumentPicker || !isStorageConfigured()) throw new Error('No storage folder has been chosen.');
  // Backups used to be written to the Datum root and now live in backups/.
  // Both are read, or every backup taken before this change becomes
  // unopenable, which for a backup feature is the worst possible failure.
  let text;
  try {
    text = await fsReadFile(joinPath(shareDir('backups'), filename));
  } catch (e) {
    text = await fsReadFile(joinPath(datumRoot(), filename));
  }
  const data = JSON.parse(text);

  for (const wp of data.waypoints || []) await Store.saveWaypoint(wp);
  for (const r of data.routes || []) await Store.saveRoute(r);
  for (const t of data.tracks || []) await Store.saveTrack(t);
  // Sessions were previously gathered into the backup but never restored from
  // it, so every restore silently lost them. saveSession(name) snapshots
  // whatever is currently loaded rather than accepting a record, so the stored
  // snapshot is written directly instead of going through it.
  for (const sess of data.sessions || []) {
    if (sess && sess.id) await Store.putSession(sess);
  }

  if (data.layerStack) localStorage.setItem('layerStack', JSON.stringify(data.layerStack));
  if (data.layerPresets) localStorage.setItem('layerPresets', JSON.stringify(data.layerPresets));
  if (data.savedRegions) localStorage.setItem('savedRegions', JSON.stringify(data.savedRegions));

  return data;
}

// Lists both the new backups/ folder and the old root location, so backups
// taken before the folder split stay visible and restorable.
export async function listBackupFiles() {
  if (!CapDocumentPicker || !isStorageConfigured()) return [];
  const names = new Set(await listShareFiles('backups', '.json'));
  try {
    (await fsReaddir(datumRoot()))
      .filter(f => (f.type || '') !== 'directory')
      .map(f => f.name)
      // Only backup blobs from the root, not README.txt and not the share
      // folders that now sit alongside it.
      .filter(n => n.startsWith('datum-backup-') && n.endsWith('.json'))
      .forEach(n => names.add(n));
  } catch (e) { /* root unreadable, the new folder alone is fine */ }
  return Array.from(names).sort().reverse();
}
